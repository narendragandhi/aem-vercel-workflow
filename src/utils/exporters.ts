/**
 * Exports workflow as comprehensive Markdown documentation.
 *
 * Generates rich documentation including:
 * - Overview with workflow statistics
 * - Detailed step descriptions grouped by type
 * - Participant responsibility matrix
 * - Embedded Mermaid flow diagram
 * - Connection mappings (from/to)
 *
 * @param {Node[]} nodes - Array of ReactFlow nodes representing workflow steps
 * @param {Edge[]} edges - Array of ReactFlow edges representing transitions
 * @param {ExportOptions} [options={}] - Export configuration options
 * @returns {string} Markdown documentation with embedded Mermaid diagram
 *
 * @example
 * const markdown = exportToMarkdown(nodes, edges, {
 *   workflowName: 'Content Approval Workflow',
 *   workflowDescription: 'Three-level content review process',
 *   author: 'Content Operations Team'
 * });
 *
 * // Render in GitHub, GitLab, or any Mermaid-compatible viewer
 */
export const exportToMarkdown = (
  nodes: Node[],
  edges: Edge[],
  options: ExportOptions = {}
): string => {
  const {
    workflowName = 'Custom Workflow',
    workflowDescription = '',
    author = 'AEMFlow',
  } = options;

  const workflowNodes = nodes.filter(n => n.type !== 'startEnd');
  const branchNodes = nodes.filter(n => n.type === 'branch');
  const participantNodes = nodes.filter(n =>
    n.type === 'aemStep' || n.type === 'participantChooser'
  );

  let md = `# ${workflowName}

${workflowDescription}

---

## Overview

| Metric | Value |
|--------|-------|
| Total Steps | ${workflowNodes.length} |
| Decision Points | ${branchNodes.length} |
| Human Tasks | ${participantNodes.length} |
| Connections | ${edges.length} |
| Generated | ${new Date().toLocaleDateString()} |
| Author | ${author} |

---

## Workflow Steps

`;

  // Group nodes by type
  const nodesByType: Record<string, Node[]> = {};
  workflowNodes.forEach(node => {
    const type = node.type || 'other';
    if (!nodesByType[type]) nodesByType[type] = [];
    nodesByType[type].push(node);
  });

  const typeLabels: Record<string, string> = {
    aemStep: 'Participant Steps',
    processStep: 'Process Steps',
    branch: 'Decision Points',
    emailNotification: 'Notifications',
    damUpdate: 'DAM Operations',
    damMetadata: 'Metadata Operations',
    damTranscode: 'Transcoding Steps',
    formsProcess: 'Form Processing',
    pageActivation: 'Publishing Steps',
    callWorkflow: 'Sub-Workflows',
    participantChooser: 'Dynamic Assignment',
    graniteRouting: 'Routing Steps',
  };

  Object.entries(nodesByType).forEach(([type, typeNodes]) => {
    md += `### ${typeLabels[type] || type}\n\n`;

    typeNodes.forEach(node => {
      md += `#### ${node.data?.label || node.id}\n\n`;

      if (node.data?.description) {
        md += `${node.data.description}\n\n`;
      }

      md += `| Property | Value |\n`;
      md += `|----------|-------|\n`;
      md += `| Type | \`${type}\` |\n`;

      if (node.data?.participant) {
        md += `| Participant | ${node.data.participant} |\n`;
      }

      if (node.data?.timeout) {
        md += `| Timeout | ${node.data.timeout} minutes |\n`;
      }

      if (node.data?.processHandler) {
        md += `| Handler | \`${node.data.processHandler}\` |\n`;
      }

      // Find connections
      const incoming = edges.filter(e => e.target === node.id);
      const outgoing = edges.filter(e => e.source === node.id);

      if (incoming.length > 0) {
        const incomingLabels = incoming.map(e => {
          const sourceNode = nodes.find(n => n.id === e.source);
          return sourceNode?.data?.label || e.source;
        }).join(', ');
        md += `| From | ${incomingLabels} |\n`;
      }

      if (outgoing.length > 0) {
        const outgoingLabels = outgoing.map(e => {
          const targetNode = nodes.find(n => n.id === e.target);
          const label = e.label ? ` (${e.label})` : '';
          return (targetNode?.data?.label || e.target) + label;
        }).join(', ');
        md += `| To | ${outgoingLabels} |\n`;
      }

      md += '\n';
    });
  });

  // Add flow diagram (Mermaid)
  md += `---

## Flow Diagram

\`\`\`mermaid
${generateMermaidDiagram(nodes, edges)}
\`\`\`

---

## Participants

| Participant | Steps |
|-------------|-------|
`;

  const participantSteps: Record<string, string[]> = {};
  nodes.forEach(node => {
    if (node.data?.participant) {
      if (!participantSteps[node.data.participant]) {
        participantSteps[node.data.participant] = [];
      }
      participantSteps[node.data.participant].push(node.data.label || node.id);
    }
  });

  Object.entries(participantSteps).forEach(([participant, steps]) => {
    md += `| ${participant} | ${steps.join(', ')} |\n`;
  });

  md += `
---

*Documentation generated by AEMFlow*
`;

  return md;
};

