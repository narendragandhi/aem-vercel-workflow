/**
 * Generates a Mermaid flowchart diagram from workflow nodes and edges.
 *
 * Creates a visual representation using Mermaid syntax that can be
 * rendered in:
 * - GitHub/GitLab Markdown
 * - Notion, Confluence, and other documentation tools
 * - Mermaid Live Editor
 * - HTML pages with Mermaid.js
 *
 * Node shapes are determined by type:
 * - Start/End: Circle/Double circle
 * - Branch: Diamond (decision)
 * - Process: Parallelogram
 * - Others: Rectangle
 *
 * @param {Node[]} nodes - Array of ReactFlow nodes representing workflow steps
 * @param {Edge[]} edges - Array of ReactFlow edges representing transitions
 * @returns {string} Mermaid flowchart syntax
 *
 * @example
 * const mermaid = generateMermaidDiagram(nodes, edges);
 *
 * // Use in Markdown:
 * // ```mermaid
 * // ${mermaid}
 * // ```
 *
 * @see {@link https://mermaid.js.org/syntax/flowchart.html|Mermaid Flowchart Syntax}
 */
export const generateMermaidDiagram = (
  nodes: Node[],
  edges: Edge[]
): string => {
  let mermaid = 'flowchart TD\n';

  // Define nodes
  nodes.forEach(node => {
    const id = sanitizeMermaidId(node.id);
    const label = node.data?.label || node.id;

    if (node.type === 'startEnd') {
      if (node.data?.isStart) {
        mermaid += `    ${id}((${label}))\n`;
      } else {
        mermaid += `    ${id}(((${label})))\n`;
      }
    } else if (node.type === 'branch') {
      mermaid += `    ${id}{${label}}\n`;
    } else if (node.type === 'processStep' || node.type === 'damUpdate' || node.type === 'damTranscode') {
      mermaid += `    ${id}[/${label}/]\n`;
    } else {
      mermaid += `    ${id}[${label}]\n`;
    }
  });

  mermaid += '\n';

  // Define edges
  edges.forEach(edge => {
    const sourceId = sanitizeMermaidId(edge.source);
    const targetId = sanitizeMermaidId(edge.target);

    if (edge.label) {
      mermaid += `    ${sourceId} -->|${edge.label}| ${targetId}\n`;
    } else {
      mermaid += `    ${sourceId} --> ${targetId}\n`;
    }
  });

  // Add styling
  mermaid += '\n';
  mermaid += '    classDef startEnd fill:#10b981,stroke:#059669,color:#fff\n';
  mermaid += '    classDef branch fill:#8b5cf6,stroke:#7c3aed,color:#fff\n';
  mermaid += '    classDef process fill:#f59e0b,stroke:#d97706,color:#fff\n';
  mermaid += '    classDef participant fill:#3b82f6,stroke:#2563eb,color:#fff\n';

  // Apply classes
  nodes.forEach(node => {
    const id = sanitizeMermaidId(node.id);
    if (node.type === 'startEnd') {
      mermaid += `    class ${id} startEnd\n`;
    } else if (node.type === 'branch') {
      mermaid += `    class ${id} branch\n`;
    } else if (node.type === 'processStep' || node.type === 'damUpdate') {
      mermaid += `    class ${id} process\n`;
    } else if (node.type === 'aemStep' || node.type === 'participantChooser') {
      mermaid += `    class ${id} participant\n`;
    }
  });

  return mermaid;
};

