/**
 * Exports workflow to JSON format for backup and transfer.
 *
 * Creates a portable JSON representation of the workflow that can be:
 * - Stored in version control systems
 * - Transferred between AEMFlow instances
 * - Used for workflow backup and restore
 * - Processed by external tools
 *
 * @param {Node[]} nodes - Array of ReactFlow nodes representing workflow steps
 * @param {Edge[]} edges - Array of ReactFlow edges representing transitions
 * @param {ExportOptions} [options={}] - Export configuration options
 * @returns {string} JSON string representation of the workflow
 *
 * @example
 * const json = exportToJSON(nodes, edges, {
 *   includePositions: true,
 *   prettyPrint: true
 * });
 *
 * // Save to file
 * downloadFile(json, 'workflow.json', 'application/json');
 *
 * @throws {Error} Never throws - returns empty workflow if nodes/edges are invalid
 */
export const exportToJSON = (
  nodes: Node[],
  edges: Edge[],
  options: ExportOptions = {}
): string => {
  const {
    includeMetadata = true,
    includePositions = true,
    prettyPrint = true,
    workflowName = 'Custom Workflow',
    workflowDescription = '',
    author = 'AEMFlow',
  } = options;

  const workflow: any = {
    version: '1.0',
    format: 'aemflow-json',
  };

  if (includeMetadata) {
    workflow.metadata = {
      name: workflowName,
      description: workflowDescription,
      author,
      createdAt: new Date().toISOString(),
      nodeCount: nodes.length,
      edgeCount: edges.length,
    };
  }

  workflow.nodes = nodes.map(node => {
    const exportNode: any = {
      id: node.id,
      type: node.type,
      data: { ...node.data },
    };

    if (includePositions) {
      exportNode.position = node.position;
    }

    return exportNode;
  });

  workflow.edges = edges.map(edge => ({
    id: edge.id,
    source: edge.source,
    target: edge.target,
    sourceHandle: edge.sourceHandle,
    targetHandle: edge.targetHandle,
    label: edge.label,
  }));

  return prettyPrint
    ? JSON.stringify(workflow, null, 2)
    : JSON.stringify(workflow);
};

