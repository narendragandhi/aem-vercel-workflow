/**
 * Sanitizes an ID string for use in AEM XML node names.
 *
 * Replaces any characters that are not alphanumeric, underscore, or hyphen
 * with underscores to ensure valid XML element names.
 *
 * @param {string} id - The original ID string
 * @returns {string} Sanitized ID safe for XML element names
 * @private
 */
const sanitizeId = (id: string): string => {
  return id.replace(/[^a-zA-Z0-9_-]/g, '_');
};

/**
 * Sanitizes an ID string for use in Mermaid diagram node identifiers.
 *
 * Mermaid has stricter ID requirements than XML, so this removes
 * all non-alphanumeric characters.
 *
 * @param {string} id - The original ID string
 * @returns {string} Sanitized ID safe for Mermaid syntax
 * @private
 */
const sanitizeMermaidId = (id: string): string => {
  return id.replace(/[^a-zA-Z0-9]/g, '_');
};

/**
 * Escapes special XML characters in a string.
 *
 * Converts the following characters to their XML entity equivalents:
 * - & → &amp;
 * - < → &lt;
 * - > → &gt;
 * - " → &quot;
 * - ' → &apos;
 *
 * @param {string} str - The string to escape
 * @returns {string} XML-safe escaped string
 * @private
 */
const escapeXml = (str: string): string => {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
};

