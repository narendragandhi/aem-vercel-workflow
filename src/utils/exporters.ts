/**
 * Exports workflow to Adobe Experience Manager XML format.
 *
 * Generates a complete AEM workflow model XML file that can be directly
 * deployed to an AEM instance. The output follows the CQ workflow component
 * structure with proper JCR node types and namespaces.
 *
 * @param {Node[]} nodes - Array of ReactFlow nodes representing workflow steps
 * @param {Edge[]} edges - Array of ReactFlow edges representing transitions
 * @param {ExportOptions} [options={}] - Export configuration options
 * @returns {string} Complete AEM workflow XML document
 *
 * @example
 * const xml = exportToAEMXML(nodes, edges, {
 *   workflowName: 'Content Approval',
 *   workflowDescription: 'Multi-level content review process',
 *   author: 'Content Team'
 * });
 *
 * @see {@link https://experienceleague.adobe.com/docs/experience-manager-65/developing/extending-aem/extending-workflows/workflows.html|AEM Workflows Documentation}
 */
export const exportToAEMXML = (
  nodes: Node[],
  edges: Edge[],
  options: ExportOptions = {}
): string => {
  const {
    workflowName = 'Custom Workflow',
    workflowDescription = 'Generated by AEMFlow',
    author = 'AEMFlow',
  } = options;

  const startNode = nodes.find(n => n.type === 'startEnd' && n.data?.isStart) || nodes[0];
  const endNode = nodes.find(n => n.type === 'startEnd' && !n.data?.isStart) || nodes[nodes.length - 1];
  
  // Filter out the nodes we will explicitly handle as start/end
  const otherNodes = nodes.filter(n => n.id !== startNode.id && n.id !== endNode.id);
  
  // Create a mapping of ReactFlow IDs to AEM node names (node0, node1, etc.)
  const nodeMapping: Record<string, string> = {};
  nodeMapping[startNode.id] = 'node0';
  otherNodes.forEach((node, i) => {
    nodeMapping[node.id] = `node${i + 1}`;
  });
  nodeMapping[endNode.id] = `node${otherNodes.length + 1}`;

  let xml = `<?xml version="1.0" encoding="UTF-8"?>
<jcr:root xmlns:sling="http://sling.apache.org/jcr/sling/1.0"
          xmlns:cq="http://www.day.com/jcr/cq/1.0"
          xmlns:jcr="http://www.jcp.org/jcr/1.0"
          xmlns:nt="http://www.jcp.org/jcr/nt/1.0"
          jcr:primaryType="cq:Page">
    <jcr:content
        cq:designPath="/libs/settings/wcm/designs/default"
        cq:template="/libs/cq/workflow/templates/model"
        jcr:primaryType="cq:PageContent"
        jcr:title="${escapeXml(workflowName)}"
        sling:resourceType="cq/workflow/components/pages/model">
        <flow
            jcr:primaryType="nt:unstructured"
            sling:resourceType="foundation/components/parsys">
`;

  // Standard flow nodes for the visual parsys (simplified)
  nodes.forEach((node) => {
    const nodeId = sanitizeId(node.id);
    const nodeConfig = getAEMNodeConfig(node);
    xml += `            <${nodeId}
                jcr:primaryType="nt:unstructured"
                jcr:title="${escapeXml(node.data?.label || node.id)}"
                sling:resourceType="${nodeConfig.resourceType}"/>\n`;
  });

  xml += `        </flow>
        <model
            jcr:primaryType="nt:unstructured"
            sling:resourceType="cq/workflow/components/model"
            description="${escapeXml(workflowDescription)}"
            title="${escapeXml(workflowName)}">
            <nodes jcr:primaryType="nt:unstructured">
`;

  // Export internal nodes for the engine
  nodes.forEach((node) => {
    const aemNodeName = nodeMapping[node.id];
    const nodeConfig = getAEMNodeConfig(node);
    
    xml += `                <${aemNodeName}
                    jcr:primaryType="nt:unstructured"
                    jcr:title="${escapeXml(node.data?.label || node.id)}"
                    jcr:description="${escapeXml(node.data?.description || '')}"
                    type="${node.type === 'startEnd' ? (node.data?.isStart ? 'START' : 'END') : 'STEP'}"
                    sling:resourceType="${nodeConfig.resourceType}">
                    <metaData jcr:primaryType="nt:unstructured"`;
    
    // Add attributes to metadata
    Object.entries(nodeConfig.attributes).forEach(([key, value]) => {
      xml += `\n                        ${key}="${escapeXml(String(value))}"`;
    });
    
    xml += `/>
                </${aemNodeName}>\n`;
  });

  xml += `            </nodes>
            <transitions jcr:primaryType="nt:unstructured">
`;

  // Export transitions
  edges.forEach((edge, i) => {
    const fromNode = nodeMapping[edge.source];
    const toNode = nodeMapping[edge.target];
    if (fromNode && toNode) {
      xml += `                <node${i}_node${i}
                    jcr:primaryType="nt:unstructured"
                    from="${fromNode}"
                    to="${toNode}"
                    rule="${escapeXml(typeof edge.label === 'string' ? edge.label : '')}"/>\n`;
    }
  });

  xml += `            </transitions>
        </model>
    </jcr:content>
</jcr:root>`;

  return xml;
};

