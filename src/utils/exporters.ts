/**
 * Imports a workflow from JSON format.
 *
 * Parses an AEMFlow JSON export and returns the nodes and edges
 * ready for use in ReactFlow. Validates the format version and
 * adds necessary properties for the editor.
 *
 * @param {string} jsonString - JSON string exported by AEMFlow
 * @returns {{ nodes: Node[]; edges: Edge[] }} Parsed nodes and edges
 *
 * @throws {SyntaxError} If jsonString is not valid JSON
 * @throws {Error} If format is not 'aemflow-json'
 *
 * @example
 * try {
 *   const { nodes, edges } = importFromJSON(jsonString);
 *   setNodes(nodes);
 *   setEdges(edges);
 * } catch (error) {
 *   console.error('Failed to import workflow:', error);
 * }
 */
export const importFromJSON = (jsonString: string): { nodes: Node[]; edges: Edge[] } => {
  const data = JSON.parse(jsonString);

  if (data.format !== 'aemflow-json') {
    throw new Error('Invalid AEMFlow JSON format');
  }

  return {
    nodes: data.nodes.map((node: any) => ({
      ...node,
      draggable: true,
    })),
    edges: data.edges.map((edge: any) => ({
      ...edge,
      animated: true,
    })),
  };
};

/**
 * Imports a workflow from YAML format.
 *
 * Parses an AEMFlow YAML export using a simple line-based parser.
 * Supports the standard AEMFlow YAML structure with nodes and edges
 * sections.
 *
 * Note: This is a lightweight parser designed specifically for
 * AEMFlow's YAML format. For complex YAML, consider using a
 * full YAML parser library.
 *
 * @param {string} yamlString - YAML string exported by AEMFlow
 * @returns {{ nodes: Node[]; edges: Edge[] }} Parsed nodes and edges
 *
 * @example
 * const yamlContent = `
 * nodes:
 *   - id: "start"
 *     type: startEnd
 *     label: "Start"
 *     isStart: true
 * edges:
 *   - id: "e1"
 *     source: "start"
 *     target: "step1"
 * `;
 * const { nodes, edges } = importFromYAML(yamlContent);
 */
export const importFromYAML = (yamlString: string): { nodes: Node[]; edges: Edge[] } => {
  // Simple YAML parser for our format
  const lines = yamlString.split('\n');
  const nodes: Node[] = [];
  const edges: Edge[] = [];

  let currentSection = '';
  let currentItem: any = null;

  lines.forEach(line => {
    const trimmed = line.trim();

    if (trimmed === 'nodes:') {
      currentSection = 'nodes';
    } else if (trimmed === 'edges:') {
      currentSection = 'edges';
    } else if (trimmed.startsWith('- id:')) {
      // New item
      if (currentItem) {
        if (currentSection === 'nodes') {
          nodes.push({
            ...currentItem,
            draggable: true,
            position: currentItem.position || { x: 200, y: nodes.length * 120 },
          });
        } else if (currentSection === 'edges') {
          edges.push({
            ...currentItem,
            animated: true,
          });
        }
      }
      currentItem = { id: trimmed.replace('- id:', '').trim().replace(/"/g, '') };
    } else if (currentItem && trimmed.includes(':')) {
      const [key, ...valueParts] = trimmed.split(':');
      const value = valueParts.join(':').trim().replace(/"/g, '');
      currentItem[key.trim()] = value === 'true' ? true : value === 'false' ? false : value;
    }
  });

  // Don't forget the last item
  if (currentItem) {
    if (currentSection === 'nodes') {
      nodes.push({
        ...currentItem,
        draggable: true,
        position: currentItem.position || { x: 200, y: nodes.length * 120 },
        data: {
          label: currentItem.label,
          description: currentItem.description,
          participant: currentItem.participant,
          isStart: currentItem.isStart,
        },
      });
    } else if (currentSection === 'edges') {
      edges.push({
        ...currentItem,
        animated: true,
      });
    }
  }

  return { nodes, edges };
};
