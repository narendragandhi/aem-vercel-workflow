/**
 * Downloads content as a file in the browser.
 *
 * Creates a temporary Blob URL, triggers a download, and cleans up
 * the resources. Works in all modern browsers.
 *
 * @param {string} content - The file content to download
 * @param {string} filename - Suggested filename for the download
 * @param {string} mimeType - MIME type of the content (e.g., 'application/json')
 *
 * @example
 * // Download JSON
 * downloadFile(jsonString, 'workflow.json', 'application/json');
 *
 * @example
 * // Download XML
 * downloadFile(xmlString, 'workflow.xml', 'application/xml');
 *
 * @example
 * // Download Markdown
 * downloadFile(markdownString, 'workflow-docs.md', 'text/markdown');
 */
export const downloadFile = (
  content: string,
  filename: string,
  mimeType: string
): void => {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

