/**
 * Exports workflow to YAML format for human-readable configuration.
 *
 * YAML format is ideal for:
 * - Human review and editing
 * - Configuration management systems
 * - Documentation alongside code
 * - Diff-friendly version control
 *
 * @param {Node[]} nodes - Array of ReactFlow nodes representing workflow steps
 * @param {Edge[]} edges - Array of ReactFlow edges representing transitions
 * @param {ExportOptions} [options={}] - Export configuration options
 * @returns {string} YAML representation of the workflow
 *
 * @example
 * const yaml = exportToYAML(nodes, edges, {
 *   workflowName: 'Content Approval',
 *   includePositions: false // Cleaner YAML without positions
 * });
 */
export const exportToYAML = (
  nodes: Node[],
  edges: Edge[],
  options: ExportOptions = {}
): string => {
  const {
    includeMetadata = true,
    includePositions = false,
    workflowName = 'Custom Workflow',
    workflowDescription = '',
    author = 'AEMFlow',
  } = options;

  let yaml = `# AEMFlow Workflow Definition
# Generated: ${new Date().toISOString()}

version: "1.0"
format: aemflow-yaml

`;

  if (includeMetadata) {
    yaml += `metadata:
  name: "${workflowName}"
  description: "${workflowDescription}"
  author: "${author}"
  nodeCount: ${nodes.length}
  edgeCount: ${edges.length}

`;
  }

  yaml += `nodes:\n`;

  nodes.forEach(node => {
    yaml += `  - id: "${node.id}"
    type: ${node.type}
    label: "${node.data?.label || ''}"`;

    if (node.data?.description) {
      yaml += `\n    description: "${node.data.description}"`;
    }

    if (node.data?.participant) {
      yaml += `\n    participant: "${node.data.participant}"`;
    }

    if (node.data?.isStart !== undefined) {
      yaml += `\n    isStart: ${node.data.isStart}`;
    }

    if (includePositions) {
      yaml += `\n    position:
      x: ${node.position.x}
      y: ${node.position.y}`;
    }

    yaml += '\n';
  });

  yaml += `\nedges:\n`;

  edges.forEach(edge => {
    yaml += `  - id: "${edge.id}"
    source: "${edge.source}"
    target: "${edge.target}"`;

    if (edge.sourceHandle) {
      yaml += `\n    sourceHandle: "${edge.sourceHandle}"`;
    }

    if (edge.label) {
      yaml += `\n    label: "${edge.label}"`;
    }

    yaml += '\n';
  });

  return yaml;
};

