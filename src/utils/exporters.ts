/**
 * Configuration options for workflow export operations.
 *
 * @interface ExportOptions
 * @property {boolean} [includeMetadata=true] - Include workflow metadata (name, author, timestamps)
 * @property {boolean} [includePositions=true] - Include node position coordinates
 * @property {boolean} [includeDescription=false] - Include step descriptions
 * @property {boolean} [prettyPrint=true] - Format output with indentation (JSON/YAML)
 * @property {string} [workflowName='Custom Workflow'] - Name of the workflow
 * @property {string} [workflowDescription=''] - Description of the workflow
 * @property {string} [author='AEMFlow'] - Author attribution
 *
 * @example
 * const options: ExportOptions = {
 *   workflowName: 'Content Review Process',
 *   author: 'Content Team',
 *   includeMetadata: true,
 *   prettyPrint: true
 * };
 */
export interface ExportOptions {
  /** Include workflow metadata (name, author, timestamps) */
  includeMetadata?: boolean;
  /** Include node position coordinates */
  includePositions?: boolean;
  /** Include step descriptions */
  includeDescription?: boolean;
  /** Format output with indentation (JSON/YAML) */
  prettyPrint?: boolean;
  /** Name of the workflow */
  workflowName?: string;
  /** Description of the workflow */
  workflowDescription?: string;
  /** Author attribution */
  author?: string;
}

